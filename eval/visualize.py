import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
import os

sns.set_theme(style="whitegrid", context="paper", font_scale=1.5)

def plot_time_series(history_csv="data/adaptive_run_stats_history.csv", output_file="eval/timeseries_plot.png"):
    if not os.path.exists(history_csv):
        print(f"Skipping time-series plot. File not found: {history_csv} \n-> Please run locust with: locust -f simulator/locustfile.py --csv=data/adaptive_run")
        return
        
    df = pd.read_csv(history_csv)
    
    df['run_time'] = df['Timestamp'] - df['Timestamp'].min()
    
    # Idealized AI step limit based on phases
    df['ai_limit'] = 100
    df.loc[(df['run_time'] >= 60) & (df['run_time'] <= 120), 'ai_limit'] = 20
    
    plt.figure(figsize=(10, 5), dpi=300)
    plt.plot(df['run_time'], df['Requests/s'], label='Incoming Traffic (RPS)', color='steelblue', linewidth=2)
    plt.step(df['run_time'], df['ai_limit'], label='Dynamic AI Limit Threshold', color='darkred', linestyle='--', linewidth=2, where='post')
    
    plt.title("Adaptive AI Rate Limiting During DDoS Attack (Simulated)")
    plt.xlabel("Time (seconds)")
    plt.ylabel("Requests Per Second (RPS)")
    plt.xlim(0, max(180, df['run_time'].max()))
    plt.ylim(0, max(210, df['Requests/s'].max() * 1.2))
    plt.axvspan(60, 120, color='red', alpha=0.1, label='DDoS Phase')
    plt.legend(loc='upper right')
    plt.tight_layout()
    plt.savefig(output_file)
    print(f"Time-series plot saved to {output_file}")


def plot_latency_boxplot(output_file="eval/latency_boxplot.png"):
    # Read stats_history files to get real latency distributions
    def get_latency_dist(filepath, label):
        if not os.path.exists(filepath):
            print(f"Warning: {filepath} not found.")
            return pd.DataFrame()
            
        df = pd.read_csv(filepath)
        # Using the column generated by locust: 'Total Average Response Time' or 'Average Response Time'
        # To better approximate P99 variation, we can just use the provided response time stats.
        col = 'Total Average Response Time' if 'Total Average Response Time' in df.columns else 'Average Response Time'
        if col not in df.columns:
            # Fallback
            col = df.columns[-2]
            
        metrics = df[col].dropna()
        return pd.DataFrame({'Latency_ms': metrics, 'Configuration': label})

    # 1. Without rate limiting middleware running -> baseline_run_stats_history.csv
    # 2. With a static 50 RPS limit -> static_run_stats_history.csv
    # 3. With the AI control plane running -> adaptive_run_stats_history.csv
    df_no = get_latency_dist("data/baseline_run_stats_history.csv", "No Limits")
    df_static = get_latency_dist("data/static_run_stats_history.csv", "Static Limit\n(50 RPS)")
    df_ai = get_latency_dist("data/adaptive_run_stats_history.csv", "Adaptive AI Limit")
    
    combined = pd.concat([df_no, df_static, df_ai], ignore_index=True)
    if combined.empty:
        print("No data available to plot boxplot. Please run the three locust scenarios and generate history csv files in the data/ directory.")
        return
        
    plt.figure(figsize=(8, 6), dpi=300)
    sns.boxplot(x='Configuration', y='Latency_ms', data=combined, palette='Set2')
    plt.title("Algorithm Latency Distribution Across System Configurations")
    plt.ylabel("Latency (ms)")
    plt.xlabel("")
    plt.tight_layout()
    plt.savefig(output_file)
    print(f"Boxplot saved to {output_file}")


if __name__ == "__main__":
    os.makedirs("eval", exist_ok=True)
    plot_time_series()
    plot_latency_boxplot()